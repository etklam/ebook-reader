import { chromium } from 'playwright';
const WORK = '2604d10b-0eb7-41ed-a8f4-bd8f77b5695b';
const browser = await chromium.launch({ executablePath: process.env.PW_EXE });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
page.on('pageerror', (e) => console.log('PAGE ERROR:', e.message));
await page.goto(`http://localhost:5173/read/${WORK}`);
await page.waitForSelector('[data-paragraph-index="0"]');
await page.locator('.reader-scroll').evaluate((el) => { el.scrollTop = 600; });
await page.waitForTimeout(700);
await page.mouse.click(195, 422);
await page.getByRole('button', { name: '設定' }).click();
await page.getByRole('button', { name: '簡體' }).click();
await page.waitForTimeout(1500);
await page.getByRole('button', { name: '深色' }).click();
await page.getByRole('button', { name: '分頁' }).click();
await page.waitForTimeout(500);
console.log('pageinfo:', await page.locator('.reader-pageinfo').textContent());
await page.keyboard.press('Escape');
await page.screenshot({ path: '/tmp/s3b.png' });
await page.reload();
await page.waitForSelector('[data-paragraph-index]');
await page.waitForTimeout(600);
console.log('reload: paginated =', await page.locator('[data-mode="paginated"]').count() === 1);
await page.screenshot({ path: '/tmp/s4b.png' });
await browser.close();
console.log('done');
